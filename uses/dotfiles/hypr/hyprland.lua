hl.on("hyprland.start", function () 
    hl.exec_cmd("killall -q waybar; waybar &")
    hl.exec_cmd("killall -q hyprpaper; hyprpaper &")
    
    hl.exec_cmd("hyprctl keyword windowrulev2 'float, class:^(org.gnome.Calendar)$'")
    hl.exec_cmd("hyprctl keyword windowrulev2 'size 900 650, class:^(org.gnome.Calendar)$'")
    hl.exec_cmd("hyprctl keyword windowrulev2 'center, class:^(org.gnome.Calendar)$'")

    hl.exec_cmd("hyprctl keyword layerrule 'blur, logout_dialog'")
    hl.exec_cmd("hyprctl keyword layerrule 'ignorealpha 0.5, logout_dialog'")

    hl.exec_cmd("hyprctl keyword layerrule 'blur, wofi'")

    hl.exec_cmd("hyprctl keyword layerrule 'ignorealpha 0.5, wofi'")
    hl.exec_cmd("hyprctl keyword layerrule 'blur, notifications'")
    hl.exec_cmd("hyprctl keyword layerrule 'ignorealpha 0.2, notifications'")

    -- Audio control
    hl.exec_cmd("hyprctl keyword bindel ', XF86AudioRaiseVolume, exec, wpctl set-volume @DEFAULT_AUDIO_SINK@ 5%+'")
    hl.exec_cmd("hyprctl keyword bindel ', XF86AudioLowerVolume, exec, wpctl set-volume @DEFAULT_AUDIO_SINK@ 5%-'")
    hl.exec_cmd("hyprctl keyword bindel ', XF86AudioMute, exec, wpctl set-mute @DEFAULT_AUDIO_SINK@ toggle'")

    -- Brightness control
    hl.exec_cmd("hyprctl keyword bindel ', XF86MonBrightnessUp, exec, brightnessctl set 5%+'")
    hl.exec_cmd("hyprctl keyword bindel ', XF86MonBrightnessDown, exec, brightnessctl set 5%-'")


    hl.exec_cmd("hyprsunset &")

    hl.exec_cmd("~/.config/hypr/scripts/mode-switcher.sh --default detente")

    hl.exec_cmd("rfkill unblock bluetooth")
    hl.exec_cmd("/usr/lib/hyprpolkitagent &")

    hl.exec_cmd("wl-paste --type text --watch cliphist store")
    hl.exec_cmd("wl-paste --type image --watch cliphist store")

end)

